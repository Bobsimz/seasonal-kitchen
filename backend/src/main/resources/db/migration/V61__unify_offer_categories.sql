-- V60: 상품(producer_offers) 카테고리 분류 통일.
-- 기존엔 굵은 분류("채소")와 세부 분류(잎채소/뿌리채소/열매채소/꽃채소/양념채소)가 섞여 있어
-- 상품 탭 카테고리 칩이 일관되지 않았다. 세부 채소 분류를 모두 "채소"로 합쳐
-- 최종 분류를 채소 / 과일 / 곡류 / 기타 로 통일한다.
-- 멱등 — 재실행 시 대상 행이 없어 안전.
UPDATE producer_offers
SET category = '채소'
WHERE category IN ('잎채소', '뿌리채소', '열매채소', '꽃채소', '양념채소');
